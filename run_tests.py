"""Runs every automated test and writes the real results to TEST_RESULTS.md."""
import re, sys, time, unittest, os
os.chdir(os.path.dirname(os.path.abspath(__file__))); sys.path.insert(0, "tests")
import test_app

class R(unittest.TextTestResult):
    def __init__(s, *a, **k): super().__init__(*a, **k); s.rec = {}
    def addSuccess(s, t): super().addSuccess(t); s.rec[t.id()] = "Pass"
    def addFailure(s, t, e): super().addFailure(t, e); s.rec[t.id()] = "FAIL"
    def addError(s, t, e): super().addError(t, e); s.rec[t.id()] = "ERROR"

suite = unittest.defaultTestLoader.loadTestsFromModule(test_app); t0 = time.time()
res = unittest.TextTestRunner(resultclass=R, verbosity=1).run(suite)
rows = []
for t in sorted(res.rec):
    cls, name = t.split(".")[-2:]; tc = test_app.__dict__[cls].__dict__[name]; doc = (tc.__doc__ or "").strip()
    m = re.match(r"\[(\w+)\]\s*(.*)", doc); tech, scen = (m.group(1), m.group(2)) if m else ("", doc)
    rows.append(f"| {re.match(r'test_(\w+?_\d+)', name).group(1).replace('_', '-')} | {cls} | {tech} | {scen} | {res.rec[t]} |")
mod = {"Trips": "Itinerary", "Templates": "Itinerary", "Activities": "Itinerary", "Approval": "Itinerary (approval)", "Bookings": "Booking", "Budget": "Booking / Budget", "Errors": "Cross-cutting"}
rows = [r for r in rows]
out = f"""# Automated test results
Generated by `python run_tests.py` on {time.strftime('%Y-%m-%d %H:%M:%S')} (Python {sys.version.split()[0]}).

**Ran {res.testsRun} tests - passed {res.testsRun - len(res.failures) - len(res.errors)}, failed {len(res.failures)}, errors {len(res.errors)} ({time.time() - t0:.1f}s).**

Technique tags: FT functional, VT validation, EP equivalence partitioning, BVA boundary value analysis, ST state transition, IT integration, EG error guessing.
Test data and expected results are in `tests/test_app.py` (each test asserts its expected result; Actual = result below).

| Test ID | Group | Technique | Scenario | Result |
|---|---|---|---|---|
""" + "\n".join(rows) + "\n"
open("TEST_RESULTS.md", "w", encoding="utf-8").write(out)
print(f"\nWrote TEST_RESULTS.md ({res.testsRun} tests)"); sys.exit(0 if res.wasSuccessful() else 1)
